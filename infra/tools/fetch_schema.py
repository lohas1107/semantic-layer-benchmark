"""Fetch all retail.* DDL from ClickHouse and write fixtures/retail_schema.sql.

Run once; the output is committed so every Claude-raw run sees identical prompt
context. Re-run manually if the upstream dataset schema changes.
"""
from __future__ import annotations

from rich.console import Console

from cube.config import REPO_ROOT
from cube.engines.clickhouse import make_clickhouse_engine

FIXTURE_PATH = REPO_ROOT / "fixtures" / "retail_schema.sql"
DATABASE = "retail"


def main() -> int:
    console = Console()
    client = make_clickhouse_engine()
    if not client.ping():
        console.print("[red]ClickHouse ping failed. Check .env credentials.[/red]")
        return 1

    tables_res = client.execute(
        f"SELECT name FROM system.tables WHERE database = '{DATABASE}' ORDER BY name",
        row_cap=500,
    )
    table_names = [row[0] for row in tables_res.rows]
    if not table_names:
        console.print(f"[red]No tables found in database '{DATABASE}'.[/red]")
        return 1

    console.print(f"Found {len(table_names)} tables in {DATABASE}.")

    parts: list[str] = [
        "-- Auto-generated by scripts/fetch_schema.py. Do not edit by hand.",
        f"-- Database: {DATABASE}",
        f"-- Tables: {len(table_names)}",
        "",
    ]
    for name in table_names:
        ddl_res = client.execute(f"SHOW CREATE TABLE {DATABASE}.{name}", row_cap=1)
        if not ddl_res.rows:
            console.print(f"[yellow]No DDL for {name}; skipping.[/yellow]")
            continue
        ddl = ddl_res.rows[0][0]
        parts.append(f"-- {DATABASE}.{name}")
        parts.append(ddl)
        parts.append(";")
        parts.append("")

    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text("\n".join(parts), encoding="utf-8")
    console.print(f"[green]Wrote {FIXTURE_PATH.relative_to(REPO_ROOT)} "
                  f"({FIXTURE_PATH.stat().st_size} bytes).[/green]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
