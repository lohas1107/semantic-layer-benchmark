"""Generate the PostgreSQL fixtures of the benchmark port from their sources.

1. fixtures/retail_schema.sql (ClickHouse DDL) -> fixtures/retail_schema.pg.sql
   Cube's CamelCase table/column names stay *unquoted*. PostgreSQL folds them to
   lower case, so the same text both creates the `retail` schema of the `cube`
   image variant and is what the model sees in its prompt:
   `SELECT ProductKey FROM retail.DimProduct` works as written.
2. text_to_sql_benchmark.json + fixtures/reference_sql.pg.sql (hand-translated
   PostgreSQL reference SQL) -> text_to_sql_benchmark.pg.json
   Questions, levels and tricky_aspects are copied unchanged; expected_sql is
   replaced by the PostgreSQL version and the ClickHouse original is kept as
   expected_sql_clickhouse. "-- @note" lines become translation_notes; "-- @ties"
   and "-- @deviation" become verify_ties / verify_deviation for
   docker/contoso/verify_pg_dataset.py.

Edit the sources, never the outputs. tests/test_pg_fixtures.py fails when an
output is stale.

Usage:
  uv run python scripts/pg/build_fixtures.py            # rewrite both outputs
  uv run python scripts/pg/build_fixtures.py --check    # exit 1 if any is stale
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from cube.config import REPO_ROOT

CH_DDL = REPO_ROOT / "datasets" / "clickhouse" / "schema.sql"
PG_DDL = REPO_ROOT / "datasets" / "postgres" / "schema.sql"
SRC_JSON = REPO_ROOT / "datasets" / "clickhouse" / "benchmark.json"
PG_SQL = REPO_ROOT / "datasets" / "postgres" / "reference_sql.sql"
PG_JSON = REPO_ROOT / "datasets" / "postgres" / "benchmark.json"

# --- 1. DDL ---------------------------------------------------------------

TYPE_MAP = {
    "Int32": "integer",
    "Int64": "bigint",
    "Float64": "double precision",
    "String": "text",
    "Date": "date",
}

_TABLE_RE = re.compile(r"CREATE TABLE (\w+)\.(\w+)\s*\((.*?)\)\s*ENGINE", re.S)
_COL_RE = re.compile(r"`(\w+)`\s+(Nullable\((\w+)\)|\w+)")


def pg_type(ch_type: str) -> tuple[str, bool]:
    """Return (pg_type, nullable) for a ClickHouse column type."""
    m = re.fullmatch(r"Nullable\((\w+)\)", ch_type)
    inner, nullable = (m.group(1), True) if m else (ch_type, False)
    if inner not in TYPE_MAP:
        raise ValueError(f"unmapped ClickHouse type: {ch_type}")
    return TYPE_MAP[inner], nullable


def convert_ddl(ch_ddl: str) -> str:
    tables = _TABLE_RE.findall(ch_ddl)
    if not tables:
        raise ValueError("no CREATE TABLE statements found")
    out = [
        "-- Generated by scripts/pg/build_fixtures.py from fixtures/retail_schema.sql.",
        "-- Do not edit by hand. Identifiers are unquoted, so PostgreSQL stores them",
        "-- in lower case and queries may use either spelling (unquoted).",
        f"-- Database: retail (PostgreSQL schema)  Tables: {len(tables)}",
        "",
    ]
    for schema, table, body in tables:
        cols = []
        for name, full_type, _ in _COL_RE.findall(body):
            typ, nullable = pg_type(full_type)
            cols.append(f"    {name} {typ}{'' if nullable else ' NOT NULL'}")
        out.append(f"CREATE TABLE {schema}.{table}\n(\n" + ",\n".join(cols) + "\n);\n")
    return "\n".join(out)


# --- 2. Benchmark JSON ----------------------------------------------------

_MARK_RE = re.compile(r"^-- @q(\d+)\s*$", re.M)


def parse_pg_sql(text: str) -> dict[int, tuple[str, dict]]:
    parts = _MARK_RE.split(text)
    out: dict[int, tuple[str, dict]] = {}
    for qid, body in zip(parts[1::2], parts[2::2], strict=True):
        lines = body.splitlines()
        meta = {"translation_notes": [], "verify_ties": None, "verify_deviation": None}
        for ln in lines:
            if ln.startswith("-- @note"):
                meta["translation_notes"].append(ln[len("-- @note"):].strip())
            elif ln.startswith("-- @ties"):
                meta["verify_ties"] = [int(x) for x in ln[len("-- @ties"):].split(",")]
            elif ln.startswith("-- @deviation"):
                meta["verify_deviation"] = ln[len("-- @deviation"):].strip()
        sql = "\n".join(ln for ln in lines if not ln.startswith("-- @")).strip()
        out[int(qid)] = (sql, meta)
    return out


def build_benchmark(src: dict, pg_sql: str) -> dict:
    pg = parse_pg_sql(pg_sql)
    ids = {q["id"] for q in src["questions"]}
    if set(pg) != ids:
        missing, extra = sorted(ids - set(pg)), sorted(set(pg) - ids)
        raise ValueError(f"id mismatch: missing {missing}, extra {extra}")
    out = {k: v for k, v in src.items() if k != "questions"}
    out["database"] = "retail"
    out["engine"] = "postgresql"
    out["questions"] = []
    for q in src["questions"]:
        sql, meta = pg[q["id"]]
        out["questions"].append({
            **q,
            "expected_sql": sql,
            "expected_sql_clickhouse": q["expected_sql"],
            **meta,
        })
    return out


# --- driver ---------------------------------------------------------------

def render() -> dict[Path, str]:
    """Return {output path: expected content} for every generated fixture."""
    src = json.loads(SRC_JSON.read_text(encoding="utf-8"))
    bench = build_benchmark(src, PG_SQL.read_text(encoding="utf-8"))
    return {
        PG_DDL: convert_ddl(CH_DDL.read_text(encoding="utf-8")),
        PG_JSON: json.dumps(bench, indent=2, ensure_ascii=False) + "\n",
    }


def stale_outputs() -> list[Path]:
    return [p for p, text in render().items()
            if not p.exists() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        stale = stale_outputs()
        for p in stale:
            print(f"stale: {p.relative_to(REPO_ROOT)}")
        if not stale:
            print("up to date")
        return int(bool(stale))
    for p, text in render().items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
